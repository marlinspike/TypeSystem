import type { ActionDescription, ModelDescription, TypeDescription } from "@typesys/core";
import { propertiesToTs, propertyKey, schemaToTs } from "./schema-ts.js";

export interface GenerateModelOptions {
  /** The exported interface's name. Default `Model`. */
  name?: string;
}

function members(lines: string[], indent: string): string {
  return lines.length === 0 ? "Record<never, never>" : `{\n${lines.join("\n")}\n${indent}}`;
}

function typeBlock(type: TypeDescription, indent: string): string {
  const inner = `${indent}  `;
  // Every value is optional on a Row whatever the schema requires (policy may withhold it), so the model records each as present.
  const props = members(propertiesToTs(type.properties, Object.keys(type.properties), inner), inner);
  const computed = members(
    type.computed.map((cp) => `${inner}  /** computed from ${cp.dependsOn.join(", ")} */\n${inner}  ${propertyKey(cp.name)}: ${schemaToTs(cp.schema, `${inner}  `)};`),
    inner
  );
  const rels = members(
    type.relationships.map((r) => `${inner}  ${propertyKey(r.name)}: { target: ${JSON.stringify(r.target)}; many: ${r.cardinality.endsWith("-to-many")} };`),
    inner
  );
  return [
    `${indent}${JSON.stringify(type.name)}: {`,
    `${inner}props: ${props};`,
    `${inner}computed: ${computed};`,
    `${inner}rels: ${rels};`,
    `${inner}actions: ${type.actions.length > 0 ? type.actions.map((a) => JSON.stringify(a)).join(" | ") : "never"};`,
    `${indent}};`
  ].join("\n");
}

function actionBlock(action: ActionDescription, indent: string): string {
  const inner = `${indent}  `;
  return [
    `${indent}/** ${action.description.replaceAll("*/", "*\\/")} */`,
    `${indent}${propertyKey(action.name)}: {`,
    `${inner}input: ${schemaToTs(action.inputSchema, inner)};`,
    `${inner}output: ${schemaToTs(action.outputSchema, inner)};`,
    `${inner}target: ${action.target ? JSON.stringify(action.target.type) : "null"};`,
    `${indent}};`
  ].join("\n");
}

/**
 * A model description (`describeModel(registry)`, `@typesys/core`) as one
 * TypeScript interface (ADR-0055), for `createClient<Model>()`. The output
 * imports nothing, so it can be committed beside a domain and checked for
 * drift by generating again and comparing.
 */
export function generateModel(model: ModelDescription, opts: GenerateModelOptions = {}): string {
  const name = opts.name ?? "Model";
  return [
    "// GENERATED by `typesys generate-sdk` (@typesys/sdk, ADR-0055). Do not edit by hand; regenerate.",
    "",
    `/** The model, for \`createClient<${name}>()\`. */`,
    `export interface ${name} {`,
    "  types: {",
    ...model.types.map((t) => typeBlock(t, "    ")),
    "  };",
    ...(model.actions.length === 0 ? ["  actions: Record<never, never>;"] : ["  actions: {", ...model.actions.map((a) => actionBlock(a, "    ")), "  };"]),
    "}",
    ""
  ].join("\n");
}
