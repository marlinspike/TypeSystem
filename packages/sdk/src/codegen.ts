import type { ActionDefinition, JsonSchema2020, SemanticRegistry, TypeDefinition } from "@typesys/core";
import { propertiesToTs, propertyKey, schemaToTs } from "./schema-ts.js";

export interface GenerateModelOptions {
  /** The exported interface's name. Default `Model`. */
  name?: string;
  /** Only Types (and the Actions on them) whose names start with one of these, e.g. `["airforce."]`. Relationship targets outside them are kept, so every target resolves. */
  prefixes?: string[];
}

/** A Type's stored properties as the registry composed them (ADR-0004): base, then traits, then its own, the later winning. */
async function flatProperties(registry: SemanticRegistry, typeDef: TypeDefinition): Promise<Record<string, JsonSchema2020>> {
  const base = typeDef.extends ? await registry.getType(typeDef.extends) : undefined;
  const properties: Record<string, JsonSchema2020> = base ? await flatProperties(registry, base) : {};
  for (const trait of typeDef.traits ?? []) Object.assign(properties, registry.getTraitSchema(trait)?.properties ?? {});
  Object.assign(properties, typeDef.schema.properties ?? {});
  return properties;
}

/** The Types to emit: those selected, and every Type a selected one's relationships reach, transitively. */
function closure(all: TypeDefinition[], prefixes: string[] | undefined): TypeDefinition[] {
  const byName = new Map(all.map((t) => [t.name, t]));
  const selected = prefixes ? all.filter((t) => prefixes.some((p) => t.name.startsWith(p))) : all;
  const keep = new Set<string>();
  const stack = selected.map((t) => t.name);
  while (stack.length > 0) {
    const name = stack.pop()!;
    if (keep.has(name)) continue;
    keep.add(name);
    for (const rel of byName.get(name)?.relationships ?? []) if (byName.has(rel.targetType)) stack.push(rel.targetType);
  }
  return all.filter((t) => keep.has(t.name)).sort((a, b) => a.name.localeCompare(b.name));
}

function members(lines: string[], indent: string): string {
  return lines.length === 0 ? "Record<never, never>" : `{\n${lines.join("\n")}\n${indent}}`;
}

async function typeBlock(registry: SemanticRegistry, typeDef: TypeDefinition, actions: ActionDefinition[], indent: string): Promise<string> {
  const inner = `${indent}  `;
  const properties = await flatProperties(registry, typeDef);
  // Every value is optional on a Row whatever the schema requires (policy may withhold it), so the model records each as present.
  const props = members(propertiesToTs(properties, Object.keys(properties), inner), inner);
  const computed = members(
    typeDef.computedProperties.map((cp) => {
      const doc = `${inner}  /** computed from ${cp.dependsOn.join(", ")} */\n`;
      return `${doc}${inner}  ${propertyKey(cp.name)}: ${schemaToTs(cp.schema, `${inner}  `)};`;
    }),
    inner
  );
  const rels = members(
    typeDef.relationships.map((r) => `${inner}  ${propertyKey(r.name)}: { target: ${JSON.stringify(r.targetType)}; many: ${r.cardinality.endsWith("-to-many")} };`),
    inner
  );
  const names = actions.filter((a) => a.applicableTypes.includes(typeDef.name)).map((a) => JSON.stringify(a.name));
  return [
    `${indent}${JSON.stringify(typeDef.name)}: {`,
    `${inner}props: ${props};`,
    `${inner}computed: ${computed};`,
    `${inner}rels: ${rels};`,
    `${inner}actions: ${names.length > 0 ? names.join(" | ") : "never"};`,
    `${indent}};`
  ].join("\n");
}

function actionBlock(action: ActionDefinition, indent: string): string {
  const inner = `${indent}  `;
  const target = action.target ? JSON.stringify(action.target.type ?? action.applicableTypes[0]) : "null";
  return [
    `${indent}/** ${action.description.replaceAll("*/", "*\\/")} */`,
    `${indent}${propertyKey(action.name)}: {`,
    `${inner}input: ${schemaToTs(action.inputSchema, inner)};`,
    `${inner}output: ${schemaToTs(action.outputSchema, inner)};`,
    `${inner}target: ${target};`,
    `${indent}};`
  ].join("\n");
}

/**
 * The model of a registry as one TypeScript interface (ADR-0055), for
 * `createClient<Model>()`. It imports nothing, so it can be committed beside
 * a domain and checked for drift by generating again and comparing.
 */
export async function generateModel(registry: SemanticRegistry, opts: GenerateModelOptions = {}): Promise<string> {
  const name = opts.name ?? "Model";
  const types = closure(await registry.listTypes(), opts.prefixes);
  const typeNames = new Set(types.map((t) => t.name));
  const actions = (await registry.listActions())
    .filter((a) => a.applicableTypes.some((t) => typeNames.has(t)) && (!opts.prefixes || a.applicableTypes.some((t) => opts.prefixes!.some((p) => t.startsWith(p)))))
    .sort((a, b) => a.name.localeCompare(b.name));
  const typeBlocks = await Promise.all(types.map((t) => typeBlock(registry, t, actions, "    ")));
  return [
    "// GENERATED by `typesys generate-sdk` (@typesys/sdk, ADR-0055). Do not edit by hand; regenerate.",
    "",
    `/** The ${opts.prefixes ? opts.prefixes.map((p) => p.replace(/\.$/, "")).join(", ") : "registered"} model, for \`createClient<${name}>()\`. */`,
    `export interface ${name} {`,
    "  types: {",
    ...typeBlocks,
    "  };",
    ...(actions.length === 0 ? ["  actions: Record<never, never>;"] : ["  actions: {", ...actions.map((a) => actionBlock(a, "    ")), "  };"]),
    "}",
    ""
  ].join("\n");
}
