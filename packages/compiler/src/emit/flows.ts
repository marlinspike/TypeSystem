import { canonical } from "@typesys/core";
import type { FlowInfo, AppAnalysis } from "../check.js";
import { isLiteral, isRef } from "../expr.js";
import type { Expr, ReadIR, StepIR } from "../ir.js";
import { engineNames, inputSchema } from "../skeleton.js";
import { tsType, tsTypeOf, type Ty } from "../types.js";
import { readTs, usesCombinators, valueTs } from "./reads.js";
import { comment, exprTs, fnModules, ident, moduleAlias, pascal, q, type ExprTarget } from "./ts.js";

export const GENERATED = (from: string) => `// GENERATED by \`typesys app compile\` from ${from} (ADR-0082). Do not edit: change app.json, or write TypeScript in src/extensions/.`;

/**
 * One flow as a `defineWorkflow` (ADR-0081, ADR-0082): the workflow the
 * existing engine registers, runs and audits, with each step's functions
 * written out from its expressions. Its input and each step's output are
 * typed as the checker typed them, so a handwritten extension that reads a
 * run's outputs is held to the same types.
 */
export function flowSource(info: FlowInfo, analysis: AppAnalysis): string {
  const { flow, key } = info;
  const T = pascal(key);
  const names = engineNames(flow);
  const lowered = new Map(info.lowered.map((l) => [l.ir.name, l]));

  // Steps the same condition guards share one function: the engine's AI-review rule compares conditions by identity (ADR-0057).
  const conditions = new Map<string, { name: string; expr: Expr }>();
  const whenOf = (s: { name: string; when?: Expr }): string | undefined => {
    if (s.when === undefined) return undefined;
    const k = canonical(s.when);
    let c = conditions.get(k);
    if (!c) conditions.set(k, (c = { name: `when${pascal(s.name)}`, expr: s.when }));
    return c.name;
  };

  const ctxTarget = (extra: Record<string, string> = {}): ExprTarget => ({
    ref: (head) => {
      if (Object.hasOwn(extra, head)) return extra[head]!;
      if (head === "input") return "ctx.input";
      const engine = names.get(head);
      if (!engine) throw new TypeError(`$${head} names no step of ${flow.name}`);
      return engine === head ? `out(ctx, ${q(head)})` : `out(ctx, ${q(engine)})?.${head}`;
    }
  });

  const modules = new Set<string>();
  const helpers = new Set<string>(["need"]);
  const sdk = { and: false, or: false };
  const noteRead = (r: ReadIR) => {
    const u = usesCombinators(r);
    sdk.and ||= u.and;
    sdk.or ||= u.or;
    if (r.kind === "query") helpers.add("rows");
  };

  const read = (r: { name: string; read: ReadIR; timeoutMs?: number; onError?: "fail" | "continue" }, target: ExprTarget): string => {
    noteRead(r.read);
    let call = readTs(r.read, target);
    if (r.timeoutMs !== undefined) {
      helpers.add("within");
      call = `within(${r.timeoutMs}, ${q(`read "${r.name}"`)}, () => ${call})`;
    }
    if (r.onError === "continue") {
      helpers.add("orUnknown");
      call = `orUnknown(() => ${call})`;
    }
    return call;
  };

  const base = (s: StepIR): string[] => {
    const l = lowered.get(s.name)!;
    const lines = [`name: ${q(s.name)}`];
    if (s.description) lines.push(`description: ${q(s.description)}`);
    if (l.needs.length) lines.push(`needs: [${l.needs.map(q).join(", ")}]`);
    const w = whenOf(s);
    if (w) lines.push(`when: ${w}`);
    if (s.retry) lines.push(`retry: ${JSON.stringify(s.retry)}`);
    return lines;
  };

  const steps = flow.steps.map((s) => {
    for (const m of fnModules(s)) modules.add(m);
    const props = base(s);
    const target = ctxTarget();
    switch (s.kind) {
      case "read":
        return obj([`kind: "read"`, ...props, `run: (client, ctx) => ${read(s, target)}`]);
      case "parallel": {
        helpers.add("parallel");
        const reads = s.steps.map((r) => {
          let call = read(r, target);
          if (r.when !== undefined) call = `$.holds(${exprTs(r.when, target)}) ? ${call} : Promise.resolve(undefined)`;
          return `${ident(r.name)}: () => ${call}`;
        });
        return obj([`kind: "read"`, ...props, `run: (client, ctx) =>\n        parallel({\n          ${reads.join(",\n          ")}\n        })`]);
      }
      case "forEach": {
        helpers.add("forEachBounded");
        const over = exprTs(s.over, target);
        const each = read({ name: s.name, read: s.read }, ctxTarget({ item: "item" }));
        return obj([`kind: "read"`, ...props, `run: (client, ctx) => forEachBounded(${over}, ${s.max}, ${s.concurrency ?? 4}, (item) => ${each}, ${q(typeof s.over === "string" ? s.over : "the list")})`]);
      }
      case "compute":
        return obj([`kind: "compute"`, ...props, `run: (ctx) => ${exprTs(s.value, target)}`]);
      case "check":
        helpers.add("assertHolds");
        return obj([`kind: "compute"`, ...props, `run: (ctx) => assertHolds(${exprTs(s.assert, target)}, ${q(s.message)})`]);
      case "ai": {
        const input = Object.entries(s.input).map(([k, v]) => `${ident(k)}: ${exprTs(v, target)}`);
        return obj([
          `kind: "ai"`,
          ...props,
          `model: ${q(s.model)}`,
          `prompt: ${q(s.prompt)}`,
          `input: (ctx) => ({ ${input.join(", ")} })`,
          `outputSchema: ${JSON.stringify(s.output)}`,
          ...(s.release ? [`release: ${q(s.release)}`] : [])
        ]);
      }
      case "approval": {
        const present = s.present.map((p) => `${ident(p)}: ${target.ref(p)}`);
        return obj([
          `kind: "approval"`,
          ...props,
          `policy: ${q(s.policy)}`,
          ...(s.allowSelfApproval ? ["allowSelfApproval: true"] : []),
          ...(s.deadlineMs !== undefined ? [`deadline: { afterMs: ${s.deadlineMs} }`] : []),
          `present: (ctx) => ({ ${present.join(", ")} })`
        ]);
      }
      case "action": {
        const action = analysis.model.actions.find((a) => a.name === s.action);
        const lines = [`kind: "action"`, ...props, `action: ${q(s.action)}`, `input: (ctx) => (${actionInput(s.action, s.input, target)})`];
        if (s.compensate) {
          const outTy = info.outputs.get(s.name)?.ty ?? { t: "unknown" };
          const uses = JSON.stringify(s.compensate.input);
          const usesOutput = uses.includes('"$output');
          const usesCtx = /"\$(?!output\b)/.test(uses);
          const outputTs = outTy.t === "unknown" || outTy.t !== "object" ? "(output as Record<string, unknown>)" : `(output as ${tsType(outTy)})`;
          const params = `(${usesCtx ? "ctx" : "_ctx"}${usesOutput ? ", output" : ""})`;
          lines.push(`compensate: {\n        action: ${q(s.compensate.action)},\n        input: ${params} => (${actionInput(s.compensate.action, s.compensate.input, ctxTarget({ output: outputTs }))})\n      }`);
        }
        void action;
        return obj(lines);
      }
    }
  });

  const stepsType = flow.steps.map((s) => {
    const t = info.outputs.get(s.name);
    return `  readonly ${ident(s.name)}: ${t ? tsTypeOf({ ...t, skippedBy: [] }) : "unknown"};`;
  });
  const inputType = Object.entries(info.input.fields).map(([k, f]) => `  readonly ${ident(k)}: ${tsType(f.ty)};`);
  const whens = [...conditions.values()].map((c) => `/** Shared by every step it guards, so the engine sees one condition (ADR-0057). */\nconst ${c.name} = (ctx: Ctx) => $.holds(${exprTs(c.expr, ctxTarget())});`);
  for (const c of conditions.values()) for (const m of fnModules(c.expr)) modules.add(m);

  const imports = [
    `import { defineWorkflow, type StepContext } from "@typesys/workflow";`,
    `import { $, ${[...helpers].sort().join(", ")} } from "@typesys/app";`,
    ...(sdk.and || sdk.or ? [`import { ${[sdk.and && "and", sdk.or && "or"].filter(Boolean).join(", ")} } from "@typesys/sdk";`] : []),
    `import type { AppModel } from "../model.js";`,
    ...[...modules].sort().map((m) => `import * as ${moduleAlias(m)} from "../../extensions/${m}.js";`)
  ];

  return `${GENERATED(`app.json /flows/${key}`)}
${imports.join("\n")}

/** What starting ${flow.name} takes. */
export interface ${T}Input {
${inputType.join("\n")}
}

/** Each step's output, as the checker typed it; a skipped step's is undefined. */
export interface ${T}Steps {
${stepsType.join("\n")}
}

type Ctx = StepContext<${T}Input>;
const out = <K extends keyof ${T}Steps>(ctx: Ctx, step: K): ${T}Steps[K] | undefined => ctx.output<${T}Steps[K]>(step);
${whens.length ? `\n${whens.join("\n")}\n` : ""}
/**
 * ${comment(flow.title ?? flow.name)}${flow.description ? `\n *\n * ${comment(flow.description)}` : ""}
 */
export const ${key} = defineWorkflow<AppModel, ${T}Input>({
  name: ${q(flow.name)},
  version: ${q(flow.version)},${flow.description ? `\n  description: ${q(flow.description)},` : ""}
  startPolicy: ${q(flow.startPolicy)},${flow.cancelPolicy ? `\n  cancelPolicy: ${q(flow.cancelPolicy)},` : ""}
  inputSchema: ${JSON.stringify(inputSchema(flow))},
  steps: [
${steps.join(",\n")}
  ]
});
`;

  function actionInput(action: string, input: Readonly<Record<string, Expr>>, target: ExprTarget): string {
    const a = analysis.model.actions.find((x) => x.name === action);
    const props = (a?.inputSchema.properties ?? {}) as Record<string, unknown>;
    const required = new Set(Array.isArray(a?.inputSchema.required) ? a.inputSchema.required : []);
    const entries = Object.entries(input).map(([k, v]) => {
      const literal = v === null || typeof v !== "object" ? !isRef(v) : isLiteral(v);
      // A required input is needed; an optional one may be left out when unknown.
      let value = literal ? exprTs(v, target) : required.has(k) ? valueTs(v, target, `input "${k}"`) : exprTs(v, target);
      if (!literal && Object.hasOwn(props, k) && typeOfExpr(v) === "unknown") value = `${value} as AppModel["actions"][${q(action)}]["input"][${q(k)}]`;
      return `${ident(k)}: ${value}`;
    });
    return `{ ${entries.join(", ")} }`;
  }

  /** Whether an action input expression's checked type is precise enough to need no cast: a whole step's output is not. */
  function typeOfExpr(v: Expr): "known" | "unknown" {
    if (typeof v === "string" && isRef(v)) {
      const head = v.slice(1).split(".")[0]!;
      const t = info.outputs.get(head)?.ty;
      if (!v.includes(".") && t && t.t === "object") return "unknown";
    }
    return "known";
  }
}

const obj = (lines: readonly string[]): string => `    {\n      ${lines.join(",\n      ")}\n    }`;

export type { Ty };
