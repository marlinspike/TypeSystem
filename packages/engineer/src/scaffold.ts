import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { describeModel, type ActionDescription, type JsonSchema2020 } from "@typesys/core";
import { generateModel } from "@typesys/sdk";
import type { EngineerHost } from "./host.js";
import type { MissionSpec, MissionStep, MissionValue, MissionView } from "./mission.js";

/**
 * Writes the application a mission describes (ADR-0071) into `dir`: the
 * spec, the typed client model generated from the host's model, the
 * workflow, the views, a server that serves the governed API with the
 * workflow registered, and acceptance tests generated from the spec. Every
 * file is code a person can read and change; `verify` checks whatever is
 * there, generated or edited.
 */
export async function scaffoldMission(spec: MissionSpec, host: EngineerHost, dir: string): Promise<string[]> {
  const model = await describeModel(host.registry);
  const actions = new Map(model.actions.map((a) => [a.name, a]));
  const files: Record<string, string> = {
    "mission.json": `${JSON.stringify(spec, null, 2)}\n`,
    "model.ts": generateModel(model, { name: "MissionModel" }),
    "server.ts": serverSource(spec),
    "acceptance.test.ts": acceptanceSource(),
    "tsconfig.json": `${JSON.stringify(TSCONFIG, null, 2)}\n`,
    ...(spec.workflow ? { "workflow.ts": workflowSource(spec, actions) } : {}),
    ...(spec.views?.length ? { "views.tsx": viewsSource(spec.views), "index.html": indexHtml(spec) } : {})
  };
  await mkdir(dir, { recursive: true });
  for (const [file, text] of Object.entries(files)) await writeFile(path.join(dir, file), text, "utf8");
  return Object.keys(files);
}

const HEADER = "// GENERATED by `typesys engineer scaffold` from mission.json (ADR-0071). Change the spec and scaffold again, or change this file and run `typesys engineer verify`.";

/** Strict, emitting to `dist/`, resolving packages as a bundler does: what `verify` builds with. */
const TSCONFIG = {
  compilerOptions: {
    target: "ES2023",
    lib: ["ES2023", "DOM"],
    types: ["node"],
    module: "preserve",
    moduleResolution: "bundler",
    jsx: "react-jsx",
    strict: true,
    noUncheckedIndexedAccess: true,
    skipLibCheck: true,
    resolveJsonModule: true,
    verbatimModuleSyntax: true,
    outDir: "dist",
    rootDir: "."
  },
  include: ["*.ts", "*.tsx"],
  exclude: ["dist", "*.test.ts"]
};

const q = (s: string) => JSON.stringify(s);
const ident = (s: string) => (/^[A-Za-z_$][\w$]*$/.test(s) ? s : q(s));

/** A spec value as a TypeScript expression of the step context (`ctx`), or of a compensated Action's `output`. */
function valueSource(v: MissionValue): string {
  if (typeof v !== "string" || !v.startsWith("$")) return `${JSON.stringify(v)} as const`;
  const [head, field] = v.slice(1).split(".", 2) as [string, string];
  if (head === "input") return `ctx.input.${field}`;
  if (head === "output") return `(output as Record<string, unknown>)[${q(field)}]`;
  return `ctx.output<Record<string, unknown>>(${q(head)})?.[${q(field)}]`;
}

/** The steps a value or values refer to. */
const stepsIn = (values: readonly MissionValue[]): string[] =>
  [...new Set(values.flatMap((v) => (typeof v === "string" && v.startsWith("$") && !v.startsWith("$input.") && !v.startsWith("$output.") ? [v.slice(1).split(".")[0]!] : [])))];

/** An Action's input object, each value typed as the Action's input schema says (the runtime validates it again). */
function actionInputSource(action: string, input: Readonly<Record<string, MissionValue>>, a: ActionDescription | undefined): string {
  const props: Record<string, JsonSchema2020> = a?.inputSchema.properties ?? {};
  const entries = Object.entries(input).map(([k, v]) => {
    const expr = valueSource(v);
    const literal = typeof v !== "string" || !v.startsWith("$");
    const typed = literal || v.startsWith("$input.") ? expr : props[k]?.type === "string" ? `String(${expr})` : `${expr} as MissionModel["actions"][${q(action)}]["input"][${q(k)}]`;
    return `${ident(k)}: ${typed}`;
  });
  return `({ ${entries.join(", ")} })`;
}

function stepSource(s: MissionStep, prior: readonly MissionStep[], actions: ReadonlyMap<string, ActionDescription>): string {
  const approvals = prior.filter((p) => p.kind === "approval").map((p) => p.name);
  const needs = (names: readonly string[]) => (names.length > 0 ? `\n      needs: [${[...new Set(names)].map(q).join(", ")}],` : "");
  switch (s.kind) {
    case "read":
      return `    {
      kind: "read",
      name: ${q(s.name)},${s.description ? `\n      description: ${q(s.description)},` : ""}${needs(stepsIn([s.id]))}
      run: async (client, ctx) => client.get(${q(s.type)}, String(${valueSource(s.id)}))
    }`;
    case "check":
      return `    {
      kind: "compute",
      name: ${q(s.name)},
      description: ${q(s.message)},${needs(stepsIn(s.equal))}
      run: (ctx) => {
        if (JSON.stringify(${valueSource(s.equal[0])}) !== JSON.stringify(${valueSource(s.equal[1])})) throw new Error(${q(s.message)});
        return true;
      }
    }`;
    case "approval":
      return `    {
      kind: "approval",
      name: ${q(s.name)},${needs(s.present ?? [])}
      policy: ${q(s.policy)},${s.allowSelfApproval ? "\n      allowSelfApproval: true," : ""}${s.deadlineMs !== undefined ? `\n      deadline: { afterMs: ${s.deadlineMs} },` : ""}
      present: (ctx) => ({ ${(s.present ?? []).map((p) => `${ident(p)}: ctx.output(${q(p)})`).join(", ")} })
    }`;
    case "action": {
      const comp = s.compensate
        ? `,\n      compensate: { action: ${q(s.compensate.action)}, input: (ctx, output) => ${actionInputSource(s.compensate.action, s.compensate.input, actions.get(s.compensate.action))} }`
        : "";
      return `    {
      kind: "action",
      name: ${q(s.name)},${needs([...approvals, ...stepsIn(Object.values(s.input))])}
      action: ${q(s.action)},
      input: (ctx) => ${actionInputSource(s.action, s.input, actions.get(s.action))}${comp}
    }`;
    }
  }
}

function workflowSource(spec: MissionSpec, actions: ReadonlyMap<string, ActionDescription>): string {
  const w = spec.workflow!;
  const usesOutput = w.steps.some((s) => s.kind === "action" && s.compensate && Object.values(s.compensate.input).some((v) => typeof v === "string" && v.startsWith("$output.")));
  const usesCtxInCompensation = w.steps.some((s) => s.kind === "action" && s.compensate && Object.values(s.compensate.input).some((v) => typeof v === "string" && v.startsWith("$") && !v.startsWith("$output.")));
  let source = `${HEADER}
import { defineWorkflow } from "@typesys/workflow";
import type { MissionModel } from "./model.js";

/** What starting ${w.name} takes. */
export interface MissionInput {
${w.input.map((i) => `  readonly ${ident(i)}: string;`).join("\n")}
}

/**
 * ${(w.description ?? spec.requirement).replaceAll("*/", "*\\/")}
 */
export const workflow = defineWorkflow<MissionModel, MissionInput>({
  name: ${q(w.name)},
  version: ${q(w.version)},${w.description ? `\n  description: ${q(w.description)},` : ""}
  startPolicy: ${q(w.startPolicy)},${w.cancelPolicy ? `\n  cancelPolicy: ${q(w.cancelPolicy)},` : ""}
  inputSchema: ${JSON.stringify({
    type: "object",
    properties: Object.fromEntries(w.input.map((i) => [i, { type: "string", minLength: 1 }])),
    required: w.input,
    additionalProperties: false
  })},
  steps: [
${w.steps.map((s, i) => stepSource(s, w.steps.slice(0, i), actions)).join(",\n")}
  ]
});
`;
  // An unused parameter is a lint finding in generated code a person will read: name it only when used.
  if (!usesOutput) source = source.replaceAll("input: (ctx, output) =>", usesCtxInCompensation ? "input: (ctx) =>" : "input: () =>");
  else if (!usesCtxInCompensation) source = source.replaceAll("input: (ctx, output) =>", "input: (_ctx, output) =>");
  return source;
}

function viewsSource(views: readonly MissionView[]): string {
  const view = (v: MissionView) => `/** ${v.title}: ${v.type}, as the signed-in caller may read it. */
export function ${v.name}() {
  const rows = useQuery((client) => client.from(${q(v.type)}).select(${v.fields.map(q).join(", ")}).limit(${v.limit ?? 50}), []);
  const error = errorOf(rows);
  return (
    <section data-view=${q(v.name)}>
      <h2>{${q(v.title)}}</h2>
      {error ? <p role="alert">{error.message}</p> : null}
      <table>
        <thead>
          <tr>
${v.fields.map((f) => `            <th>{${q(f)}}</th>`).join("\n")}
          </tr>
        </thead>
        <tbody>
          {dataOf(rows)?.items.map((row) => (
            <tr key={row.$id}>
${v.fields.map((f) => `              <td>{String(row[${q(f)}] ?? "")}</td>`).join("\n")}
            </tr>
          ))}
        </tbody>
      </table>
    </section>
  );
}`;
  return `${HEADER}
import { useMemo, useState } from "react";
import { createRoot } from "react-dom/client";
import { createTypeSysHooks, dataOf, errorOf } from "@typesys/react";
import { createClient, httpTransport } from "@typesys/sdk";
import type { MissionModel } from "./model.js";

const { TypeSysProvider, useQuery } = createTypeSysHooks<MissionModel>();

${views.map(view).join("\n\n")}

/** Every view, over the governed API, as whoever's token is entered: the runtime decides what each one shows. */
export function App() {
  const [token, setToken] = useState("");
  const client = useMemo(() => createClient<MissionModel>(httpTransport({ baseUrl: "/api", ...(token ? { token } : {}) })), [token]);
  return (
    <main>
      <label>
        Token <input value={token} onChange={(e) => setToken(e.target.value)} />
      </label>
      <TypeSysProvider client={client} key={token}>
${views.map((v) => `        <${v.name} />`).join("\n")}
      </TypeSysProvider>
    </main>
  );
}

const root = typeof document === "undefined" ? null : document.getElementById("root");
if (root) createRoot(root).render(<App />);
`;
}

function indexHtml(spec: MissionSpec): string {
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <link rel="icon" href="data:," />
    <title>${spec.name}</title>
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="./app.js"></script>
  </body>
</html>
`;
}

function serverSource(spec: MissionSpec): string {
  const opts = spec.host.options ? JSON.stringify(spec.host.options) : "";
  return `${HEADER}
import { existsSync } from "node:fs";
import type { AddressInfo } from "node:net";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import type { Express } from "express";
import { clientRouter, createApiApp } from "@typesys/http";
import { WorkflowEngine } from "@typesys/workflow";
import * as host from ${q(spec.host.module)};
${spec.workflow ? 'import { workflow } from "./workflow.js";\n' : ""}
/** The application: the governed API over the host${spec.workflow ? ", with its workflow registered" : ""}, and its views when they are built. */
export async function createMissionApp(): Promise<{ app: Express; workflows: WorkflowEngine }> {
  const backend = await host.${spec.host.build}(${opts});
  const workflows = await WorkflowEngine.create({ host: backend });
${spec.workflow ? "  workflows.register(workflow);\n" : ""}  const app = createApiApp({ backend, identityResolver: async (token) => host.${spec.host.identities}(token), workflows });
  const client = path.join(path.dirname(fileURLToPath(import.meta.url)), "client");
  if (existsSync(client)) app.use(clientRouter({ dir: client }));
  return { app, workflows };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { app } = await createMissionApp();
  const server = app.listen(Number(process.env.PORT ?? 4600), "127.0.0.1", () => {
    console.log(\`${spec.name} on http://127.0.0.1:\${(server.address() as AddressInfo).port}\`);
  });
}
`;
}

function acceptanceSource(): string {
  return `${HEADER}
import { readFileSync } from "node:fs";
import type { Server } from "node:http";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { runCheck, type MissionSpec } from "@typesys/engineer";
import { createMissionApp } from "./server.js";

const spec = JSON.parse(readFileSync(new URL("./mission.json", import.meta.url), "utf8")) as MissionSpec;

/** The mission's acceptance checks, each through this application's API as its caller. */
describe(spec.name, () => {
  let server: Server;
  let baseUrl = "";
  beforeAll(async () => {
    const { app } = await createMissionApp();
    server = await new Promise<Server>((resolve) => {
      const s = app.listen(0, "127.0.0.1", () => resolve(s));
    });
    baseUrl = \`http://127.0.0.1:\${(server.address() as { port: number }).port}\`;
  });
  afterAll(() => new Promise<void>((resolve) => server.close(() => resolve())));

  for (const check of spec.acceptance) {
    it(\`\${check.id}\${check.because ? \`: \${check.because}\` : ""}\`, async () => {
      const result = await runCheck(baseUrl, spec, check);
      expect(result.ok, JSON.stringify(result.observed)).toBe(true);
    });
  }
});
`;
}
